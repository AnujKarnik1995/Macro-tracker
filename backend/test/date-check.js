const fs=require('fs'), vm=require('vm'), path=require('path');
const mock=require('./mock-apps-script.js');
const sb=(mock.makeContext?mock.makeContext():Object.assign({},mock));
const logs=[]; sb.Logger={log:m=>logs.push(m)};
if(!sb.Utilities) sb.Utilities={formatDate:(d,tz,f)=>d.toISOString().slice(0,10)};
vm.createContext(sb);
vm.runInContext(fs.readFileSync(path.join(__dirname,'../Code.gs'),'utf8'), sb);
const {parseInputDate, payloadItemToRow}=sb;
let pass=0,fail=0;
const t=(n,g,w)=>{const ok=g===w;console.log(`  ${ok?'ok  ':'FAIL'}  ${n}: ${JSON.stringify(g)} (want ${JSON.stringify(w)})`);ok?pass++:fail++;};

console.log("parseInputDate:");
t("ISO  2026-08-15",        parseInputDate("2026-08-15"), "2026-08-15");
t("ISO  2026-8-5 loose",    parseInputDate("2026-8-5"),   "2026-08-05");
t("DMY  15/08/2026",        parseInputDate("15/08/2026"), "2026-08-15");
t("DMY  5/8/2026 loose",    parseInputDate("5/8/2026"),   "2026-08-05");
t("whitespace tolerated",   parseInputDate("  2026-08-15 "), "2026-08-15");
t("impossible ISO date",    parseInputDate("2026-02-30"), null);
t("impossible DMY date",    parseInputDate("30/02/2026"), null);
t("month 13 ISO",           parseInputDate("2026-13-01"), null);
t("US style rejected",      parseInputDate("08-15-2026"), null);
t("dotted rejected",        parseInputDate("2026.08.15"), null);
t("garbage",                parseInputDate("yesterday"),  null);
t("non-string",             parseInputDate(20260815),     null);
t("round-trips own output", parseInputDate(parseInputDate("15/08/2026")), "2026-08-15");

console.log("\npayloadItemToRow fallback + warning:");
const meal={meal:"Dinner",details:"Indian pizza",cal:860,p:32,c:93,f:42};
t("ISO date honoured",   payloadItemToRow(Object.assign({date:"2026-08-15"},meal),"2026-08-22").date, "2026-08-15");
t("DMY date honoured",   payloadItemToRow(Object.assign({date:"15/08/2026"},meal),"2026-08-22").date, "2026-08-15");
t("no date -> fallback", payloadItemToRow(Object.assign({},meal),"2026-08-22").date, "2026-08-22");
logs.length=0;
t("bad date -> fallback",payloadItemToRow(Object.assign({date:"Aug 15"},meal),"2026-08-22").date, "2026-08-22");
t("bad date warns",      logs.length>0 && /UNPARSEABLE DATE/.test(logs[0]), true);
logs.length=0;
payloadItemToRow(Object.assign({},meal),"2026-08-22");
t("no date does NOT warn", logs.length, 0);
console.log(`\n${pass} passed, ${fail} failed`);
process.exit(fail?1:0);
